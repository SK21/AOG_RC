#!/usr/bin/env bash
# Builds the AgIsoStack Arduino library used by RCteensy ISOBUS builds (ISOBUS_ENABLED 1)
# from an AgIsoStack++ checkout. Run from Git Bash. See README.md.
#
# Usage: make_lib.sh <AgIsoStack++ checkout> [output library folder]

set -euo pipefail

PINNED=d29e670		# AgIsoStack++ main, 2026-11-18 (tested build)

SRC="${1:?usage: make_lib.sh <AgIsoStack++ checkout> [output library folder]}"
OUT="${2:-D:/Sync/Documents/Arduino/libraries/AgIsoStack}"

[ -f "$SRC/library.json" ] || { echo "not an AgIsoStack++ checkout: $SRC"; exit 1; }

HEAD=$(git -C "$SRC" rev-parse --short=7 HEAD)
if [ "$HEAD" != "$PINNED" ]; then
	echo "warning: checkout is at $HEAD, tested commit is $PINNED"
fi

rm -rf "$OUT"
mkdir -p "$OUT/src"
L="$OUT/src"

# Sources: same set as library.json's srcFilter (Teensy only, no ESP/MCP2515 drivers).
# upstream generateArduinoLibrary.py is out of date: it removes can_hardware_interface.cpp,
# which the current Teensy build needs.
cp "$SRC"/isobus/src/*.cpp "$SRC"/utility/src/*.cpp "$L/"
cp "$SRC"/hardware_integration/src/can_hardware_interface.cpp \
   "$SRC"/hardware_integration/src/flex_can_t4_plugin.cpp "$L/"

# Headers
cp "$SRC"/isobus/include/isobus/isobus/*.hpp "$SRC"/utility/include/isobus/utility/*.hpp "$L/"
for h in can_hardware_interface can_hardware_plugin flex_can_t4_plugin; do
	cp "$SRC/hardware_integration/include/isobus/hardware_integration/$h.hpp" "$L/"
done
cp "$SRC"/hardware_integration/lib/Teensy/FlexCan_T4/* "$L/"

# Flat folder: drop the include path prefixes
sed -i 's#isobus/isobus/##g; s#isobus/utility/##g; s#isobus/hardware_integration/##g' "$L"/*.cpp "$L"/*.hpp

# The DDI name table (68 KB RAM1 plus 56 KB of startup code) is only used for log text
sed -i '0,/#define ISOBUS_DATA_DICTIONARY_HPP/s//#define ISOBUS_DATA_DICTIONARY_HPP\n#define DISABLE_ISOBUS_DATA_DICTIONARY \/\/ added by make_lib.sh: saves 124 KB of RAM1/' \
	"$L/isobus_data_dictionary.hpp"
grep -q DISABLE_ISOBUS_DATA_DICTIONARY "$L/isobus_data_dictionary.hpp" || { echo "data dictionary patch failed"; exit 1; }

# Umbrella header. Leaves out the FlexCAN internals and the VT/TC server headers
# (servers need std::mutex and aren't used on a module).
{
	echo "// AgIsoStack.hpp - generated by make_lib.sh from AgIsoStack++ $HEAD"
	echo "#ifndef AG_ISO_STACK_HPP"
	echo "#define AG_ISO_STACK_HPP"
	for h in "$L"/*.hpp; do
		n=$(basename "$h")
		case "$n" in
			AgIsoStack.hpp|FlexCAN_T4.hpp|imxrt_flexcan.hpp|kinetis_flexcan.hpp|circular_buffer.hpp) ;;
			*virtual_terminal_server*|*virtual_terminal_working_set_base*|*task_controller_server*) ;;
			*) echo "#include \"$n\"" ;;
		esac
	done
	echo "#endif"
} > "$L/AgIsoStack.hpp"

cat > "$OUT/library.properties" <<EOP
name=AgIsoStack
version=1.0.0
author=The Open-Agriculture Developers
maintainer=The Open-Agriculture Developers
sentence=AgIsoStack++ $HEAD for Teensy 4.x, generated by RateControl make_lib.sh
paragraph=ISOBUS (ISO 11783) and J1939 CAN stack.
category=Communication
url=https://github.com/Open-Agriculture/AgIsoStack-plus-plus
architectures=teensy
includes=AgIsoStack.hpp
EOP

echo "AgIsoStack $HEAD -> $OUT ($(ls "$L" | wc -l) files)"
